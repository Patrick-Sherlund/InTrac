import hashlib
import io
import json
from datetime import datetime, timezone
from itertools import chain

from PIL import Image
from pypdf import PdfReader, PdfWriter
from pypdf.generic import NameObject, NumberObject, TextStringObject
from reportlab.lib.colors import HexColor, white
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

from app.report_photo_pages import render_photo_pages
from app.storage import weapon_serial_numbers


PHOTO_EXTENSIONS = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}


def _add_attachment(writer: PdfWriter, filename: str, content: bytes, content_type: str, description: str) -> None:
    attachment = writer.add_attachment(filename, content)
    attachment.description = TextStringObject(description)
    attachment.subtype = NameObject(f"/{content_type}")
    attachment.size = NumberObject(len(content))


def _metadata_text(metadata: dict) -> bytes:
    lines = [
        "InTrac - Photo attachment index",
        f"Generated at (UTC): {metadata['generated_at']}",
        f"Generated by: {metadata['generated_by']}",
        f"Attached photos: {len(metadata['photos'])}",
        "",
        "Each photo contains the exact bytes stored with its weapon record, including any embedded image metadata.",
        "Operation and record timestamps below are not camera capture timestamps.",
        "",
    ]

    def display(value):
        return "Not recorded" if value is None or value == "" else str(value)

    for entry in metadata["photos"]:
        log, weapon, photo = entry["log"], entry["weapon"], entry["photo"]
        recorder = log["recorded_by"]
        lines.extend([
            f"Photo: {entry['filename']}",
            f"Operation ID: {log['id']}",
            f"Operation name: {log['operation_name']}",
            f"Operation date/time: {log['occurred_at']}",
            f"Operation record created at: {log['created_at']}",
            f"LAF Soldier Name: {display(log['laf_soldier_name'])}",
            f"Location: {log['location_name']}",
            f"Latitude: {display(log['latitude'])}",
            f"Longitude: {display(log['longitude'])}",
            f"Location accuracy (meters): {display(log['location_accuracy'])}",
            f"Status: {log['status']}",
            f"Verified at: {display(log['verified_at'])}",
            f"Verified by: {display(log['verified_by'])}",
            f"Recorded by: {recorder['first_name']} {recorder['last_name']} ({recorder['username']})",
            f"Weapon record ID: {weapon['id']}",
            f"Weapon type: {weapon['item_type']}",
            f"Name/model: {display(weapon['name_model'])}",
            f"Quantity: {weapon['quantity']}",
            "Serial numbers:",
            *[f"  {serial}" for serial in weapon["serial_numbers"] or ["Not recorded"]],
            f"Weapon record created at: {weapon['created_at']}",
            f"Photo content type: {photo['content_type']}",
            f"Photo size (bytes): {photo['size_bytes']}",
            f"Photo dimensions (pixels): {photo['width']} x {photo['height']}",
            f"Photo SHA-256: {photo['sha256']}",
            "",
        ])
    return ("\n".join(lines) + "\n").encode("utf-8")


def embed_report_photos(summary_pdf: bytes, connection, user_id: int, log_ids: list[int],
                        username: str, generated_at: datetime) -> bytes:
    rows = connection.execute(
        "SELECT operation_logs.id AS log_id, operation_logs.operation_name, operation_logs.occurred_at, "
        "operation_logs.created_at AS log_created_at, operation_logs.operator_name, operation_logs.location_name, "
        "operation_logs.latitude, operation_logs.longitude, operation_logs.location_accuracy, operation_logs.status, "
        "operation_logs.reviewed_at, operation_logs.reviewed_by_name, users.username, users.first_name, users.last_name, "
        "weapons.id AS weapon_id, weapons.item_type, weapons.name_model, weapons.quantity, "
        "weapons.serial_number, weapons.serial_numbers, weapons.created_at AS weapon_created_at, "
        "weapons.photo, weapons.photo_content_type "
        "FROM operation_logs JOIN weapons ON weapons.log_id = operation_logs.id "
        "JOIN users ON users.id = operation_logs.user_id "
        "WHERE operation_logs.user_id = ? AND operation_logs.id IN (SELECT value FROM json_each(?)) "
        "AND weapons.photo IS NOT NULL ORDER BY operation_logs.id, weapons.id",
        (user_id, json.dumps(log_ids)),
    )
    first_photo = rows.fetchone()
    if first_photo is None:
        return summary_pdf

    writer = PdfWriter()
    writer.clone_document_from_reader(PdfReader(io.BytesIO(summary_pdf)))
    writer.page_mode = "/UseNone"
    metadata = {
        "generated_at": generated_at.astimezone(timezone.utc).isoformat(),
        "generated_by": username,
        "photos": [],
    }
    for row in chain((first_photo,), rows):
        content = row["photo"]
        content_type = row["photo_content_type"]
        filename = f"log-{row['log_id']}-weapon-{row['weapon_id']}.{PHOTO_EXTENSIONS[content_type]}"
        with Image.open(io.BytesIO(content)) as photo:
            width, height = photo.size
        metadata["photos"].append({
            "filename": filename,
            "log": {
                "id": row["log_id"], "operation_name": row["operation_name"],
                "occurred_at": row["occurred_at"], "created_at": row["log_created_at"],
                "laf_soldier_name": row["operator_name"], "location_name": row["location_name"],
                "latitude": row["latitude"], "longitude": row["longitude"],
                "location_accuracy": row["location_accuracy"],
                "status": "Verified" if row["status"] == "REVIEWED" else "Unverified",
                "verified_at": row["reviewed_at"], "verified_by": row["reviewed_by_name"],
                "recorded_by": {key: row[key] for key in ("username", "first_name", "last_name")},
            },
            "weapon": {
                "id": row["weapon_id"], "item_type": row["item_type"], "name_model": row["name_model"],
                "quantity": row["quantity"], "serial_numbers": weapon_serial_numbers(row),
                "created_at": row["weapon_created_at"],
            },
            "photo": {
                "content_type": content_type, "size_bytes": len(content), "width": width, "height": height,
                "sha256": hashlib.sha256(content).hexdigest(),
            },
        })
        _add_attachment(writer, filename, content, content_type,
                        f"Original photo for weapon {row['weapon_id']} in operation {row['log_id']}: {row['operation_name']}")
        photo_pages = PdfReader(io.BytesIO(render_photo_pages(metadata["photos"][-1], content)))
        for page in photo_pages.pages:
            writer.add_page(page)

    _add_attachment(writer, "photo-metadata.json", json.dumps(metadata, ensure_ascii=False, indent=2).encode("utf-8"),
                    "application/json", "Photo index with operation, weapon, location, verification and file metadata.")
    _add_attachment(writer, "photo-metadata.txt", _metadata_text(metadata),
                    "text/plain", "Human-readable photo index with operation, weapon and file metadata.")
    page_numbers = io.BytesIO()
    numbering = canvas.Canvas(page_numbers, pagesize=letter)
    for page_number in range(1, len(writer.pages) + 1):
        numbering.setFillColor(white)
        numbering.rect(474, 25, 100, 18, fill=1, stroke=0)
        numbering.setFillColor(HexColor("#58717D"))
        numbering.setFont("Helvetica", 7.5)
        numbering.drawRightString(570, 32, f"{page_number} / {len(writer.pages)}")
        numbering.showPage()
    numbering.save()
    for page, numbers in zip(writer.pages, PdfReader(page_numbers).pages):
        page.merge_page(numbers)
    output = io.BytesIO()
    writer.write(output)
    return output.getvalue()
